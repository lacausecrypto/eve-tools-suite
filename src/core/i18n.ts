const DICTS: Record<Language, Dict> = { fr, en };

/**
 * Enregistre des traductions **propres à un module** dans les dictionnaires
 * partagés (clés préfixées par l'id du module). Appelé à l'import du module,
 * donc avant le premier rendu. Garde les outils localisés et auto-contenus.
 */
export function registerMessages(messages: { fr: Dict; en: Dict }): void {
  Object.assign(fr, messages.fr);
  Object.assign(en, messages.en);
}

function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) =>
    k in vars ? String(vars[k]) : `{${k}}`,
  );
}

/** Traduit une clé dans une langue donnée (repli sur le français puis la clé). */
export function translate(key: string, lang: Language, vars?: Vars): string {
  const s = DICTS[lang]?.[key] ?? fr[key] ?? key;
  return interpolate(s, vars);
}

/** Langue courante (hors React). */
export function currentLang(): Language {
  return useSettings.getState().language;
}

/** Traduction impérative (toasts, code hors composant). Non réactif. */
export function t(key: string, vars?: Vars): string {
  return translate(key, currentLang(), vars);
}

/** Hook de traduction **réactif** : re-render au changement de langue. */
export function useT(): (key: string, vars?: Vars) => string {
  const lang = useSettings((s) => s.language);
  return (key, vars) => translate(key, lang, vars);
}

/** Résout un `LocalizedText` dans la langue courante (ou fournie). */
export function localized(value: LocalizedText, lang?: Language): string {
  if (typeof value === "string") return value;
  const l = lang ?? currentLang();
  return value[l] ?? value.fr ?? value.en ?? "";
}

/** Hook réactif pour résoudre un `LocalizedText`. */
export function useLocalized(): (value: LocalizedText) => string {
  const lang = useSettings((s) => s.language);
  return (value) => localized(value, lang);
}
